  assertNoLeak(result, root, name)
  assert.deepEqual(wholeState(root), before, `${name}: staged/index/tree state mutated`)
  assert.equal(readFileSync(graphPath(root), 'utf8'), priorGraph)
  assert.equal(readFileSync(join(root, 'generator-ran.sentinel'), 'utf8'), 'NOT-RUN\n')
  return { exit: result.status, code: envelope.detail.code, stdoutHash: sha256(result.stdout), stderrHash: sha256(result.stderr) }
