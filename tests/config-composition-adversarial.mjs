function command(tool, args, options = {}) {
  return spawnSync(tool, args, {
    encoding: 'utf8',
    maxBuffer: MAX_BUFFER,
    env: cleanEnv,
    timeout: 30_000,
    ...options,
  })
}

function assertRun(result, label, expected = 0) {
  assert.equal(result.error, undefined, `${label}: spawn error ${result.error}`)
  assert.equal(result.status, expected,
    `${label}: exit=${result.status}, expected=${expected}\nstdout=${result.stdout}\nstderr=${result.stderr}`)
  return result
}

function git(root, args, expected = 0) {
  return assertRun(command('git', ['-C', root, ...args]), `git ${args.join(' ')}`, expected)
}

function cli(root, args) {
  return command(process.execPath, [entry, '--repo', root, ...args], { cwd: root })
}

function put(root, path, value) {
  const target = join(root, path)
  mkdirSync(dirname(target), { recursive: true })
  writeFileSync(target, Buffer.isBuffer(value) || typeof value === 'string'
    ? value
    : `${JSON.stringify(value, null, 2)}\n`)
}

function composed(include, extra = {}) {
  return { compositionVersion: 1, include, zones: null, out: '.true-up/depgraph.json', ...extra }
}

function initRepo(name) {
  const root = join(runRoot, name)
  mkdirSync(root, { recursive: true })
  git(root, ['init', '-q'])
  git(root, ['config', 'user.name', 'true-up adversarial corpus'])
  git(root, ['config', 'user.email', 'adversarial@true-up.invalid'])
  put(root, 'a.md', '# A\n')
  put(root, 'b.md', '# B\n')
  put(root, 'source.md', '# source\n')
  put(root, 'generated.md', '<!-- generated by tools/gen.sh from source.md -->\n# generated\n')
  put(root, 'data.json', { items: [{ id: 'one', value: 1 }] })
  put(root, 'tools/gen.sh', '#!/bin/sh\nprintf "RAN\\n" > generator-ran.sentinel\n')
  chmodSync(join(root, 'tools/gen.sh'), 0o755)
  put(root, 'generator-ran.sentinel', 'NOT-RUN\n')
  put(root, '.true-up/depgraph.json', 'PRIOR-GRAPH-SENTINEL\n')
  put(root, '.true-up/adversarial-existing.tmp', 'PRIOR-TEMP-SENTINEL\n')
  utimesSync(graphPath(root), 946684800, 946684800)
  utimesSync(join(root, '.true-up/adversarial-existing.tmp'), 978307200, 978307200)
  return root
}

function commitAll(root, message = 'adversarial fixture') {
  git(root, ['add', '-A'])
  git(root, ['commit', '-qm', message])
}

function statRecord(path) {
  const stat = lstatSync(path, { bigint: true })
  const common = {
    ino: stat.ino.toString(),
    mode: stat.mode.toString(),
    size: stat.size.toString(),
    mtimeNs: stat.mtimeNs.toString(),
  }
  if (stat.isDirectory()) return { kind: 'directory', ...common }
  if (stat.isSymbolicLink()) return { kind: 'symlink', target: readlinkSync(path), ...common }
  if (stat.isFile()) return { kind: 'file', hash: sha256(readFileSync(path)), ...common }
  return { kind: 'other', ...common }
}

function treeSnapshot(root) {
  const state = {}
  const walk = (relative = '') => {
    const directory = join(root, relative)
    for (const item of readdirSync(directory, { withFileTypes: true })) {
      if (!relative && item.name === '.git') continue
      const path = relative ? `${relative}/${item.name}` : item.name
      state[path] = statRecord(join(root, path))
      if (item.isDirectory() && !item.isSymbolicLink()) walk(path)
    }
  }
  walk()
  return state
}

function vcsSnapshot(root) {
  const status = git(root, ['status', '--porcelain=v2', '-z', '--untracked-files=all']).stdout
  const staged = git(root, ['diff', '--cached', '--raw', '-z']).stdout
  return { statusHash: sha256(status), stagedHash: sha256(staged) }
}

function wholeState(root) {
  return { tree: treeSnapshot(root), vcs: vcsSnapshot(root) }
}

function parseEnvelope(result, label) {
  let value
  try { value = JSON.parse(result.stdout) }
  catch (error) { assert.fail(`${label}: stdout is not one JSON object: ${error}\n${result.stdout}`) }
  assert.equal(value?._v, 1, `${label}: missing _v:1`)
  assert.equal(typeof value?.ok, 'boolean', `${label}: missing boolean ok`)
  return value
}

function assertNoLeak(result, root, label) {
  for (const output of [result.stdout, result.stderr]) {
    assert(!output.includes(root), `${label}: leaked fixture absolute path`)
    assert(!output.includes(runRoot), `${label}: leaked corpus absolute path`)
  }
}

