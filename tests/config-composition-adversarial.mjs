define('root-only-literal-fragments-allow-legal-dependency-cycle-and-no-write-generator-preview', {
  include: ['config/a.json', 'config/z.json'], graphCycle: ['a.md', 'b.md'], includeCycle: false,
}, () => {
  const name = 'root-only-literal-fragments-allow-legal-dependency-cycle-and-no-write-generator-preview'
  const root = initRepo(name)
  put(root, '.true-up.json', composed(['config/z.json', 'config/a.json']))
  put(root, 'config/a.json', {
    zones: [{ path: '', visibility: 'public', audience: 'world', intent: 'cycle', rules: [] }],
    seed: [{ from: 'a.md', to: 'b.md', kind: 'derives-facts-from' }],
  })
  put(root, 'config/z.json', { seed: [
    { from: 'b.md', to: 'a.md', kind: 'derives-facts-from' },
  ] })
  commitAll(root, 'legal dependency cycle')

  const beforeBuild = wholeState(root)
  const buildResult = cli(root, ['build', '--no-write', '--json'])
  assertRun(buildResult, `${name}: no-write build`)
  const buildEnvelope = parseEnvelope(buildResult, `${name}: no-write build`)
  assert.equal(buildEnvelope.ok, true)
  const edges = buildEnvelope.graph?.edges || []
  const aToB = edges.find((edge) => edge.from === 'file:a.md' && edge.to === 'file:b.md')
  const bToA = edges.find((edge) => edge.from === 'file:b.md' && edge.to === 'file:a.md')
  assert.deepEqual(aToB?.declaredIn, { source: 'config/a.json', pointer: '/seed/0' })
  assert.deepEqual(bToA?.declaredIn, { source: 'config/z.json', pointer: '/seed/0' })
  assert.deepEqual(wholeState(root), beforeBuild, `${name}: --no-write build mutated state`)

  put(root, 'source.md', '# source changed\n')
  const beforeRun = wholeState(root)
  const runResult = cli(root, ['run', '--no-write', '--json'])
  assertRun(runResult, `${name}: no-write run`)
  const runEnvelope = parseEnvelope(runResult, `${name}: no-write run`)
  assert.equal(runEnvelope.ok, true)
  assert.equal(runEnvelope.dryRun, true)
  assert(runEnvelope.wouldRegenerate?.includes('tools/gen.sh'), `${name}: generator preview omitted`)
  assert.deepEqual(wholeState(root), beforeRun, `${name}: no-write run mutated state`)
  assert.equal(readFileSync(join(root, 'generator-ran.sentinel'), 'utf8'), 'NOT-RUN\n')
  return {
    exit: 0,
    cycleEdges: [aToB, bToA].map((edge) => [edge.from, edge.to]),
    wouldRegenerate: runEnvelope.wouldRegenerate,
    buildStdoutHash: sha256(buildResult.stdout),
    runStdoutHash: sha256(runResult.stdout),
  }
})

let cleaned = false
try {
  for (const item of cases) {
    try {
      const evidence = item.fn()
      results.push({
        name: item.name,
        status: 'pass',
        corpusSeed: `0x${CORPUS_SEED.toString(16)}`,
        minimizedFailure: item.minimal,
        minimizedHash: sha256(JSON.stringify(item.minimal)),
        evidence,
      })
      process.stdout.write(`PASS ${item.name}\n`)
    } catch (error) {
      results.push({
        name: item.name,
        status: 'fail',
        corpusSeed: `0x${CORPUS_SEED.toString(16)}`,
        minimizedFailure: item.minimal,
        minimizedHash: sha256(JSON.stringify(item.minimal)),
        message: String(error?.stack || error).split(runRoot).join('<scratch>'),
      })
      process.stdout.write(`FAIL ${item.name}: ${String(error?.message || error).split('\n')[0]}\n`)
    }
  }
} finally {
  rmSync(runRoot, { recursive: true, force: true })
  cleaned = !existsSync(runRoot)
}

const counts = {
  pass: results.filter((result) => result.status === 'pass').length,
  fail: results.filter((result) => result.status === 'fail').length,
}
const report = {
  _v: 1,
  suite: 'config-composition-adversarial',
  corpusSeed: `0x${CORPUS_SEED.toString(16)}`,
  entry: { path: entry, sha256: sha256(readFileSync(entry)) },
  test: { path: fileURLToPath(import.meta.url), sha256: sha256(readFileSync(fileURLToPath(import.meta.url))) },
  environment: {
    node: process.version,
    git: command('git', ['--version']).stdout.trim(),
  },
  fixturePolicy: { base: scratchBase, cleaned },
  counts,
  results,
}
if (reportArg) {
  mkdirSync(dirname(reportArg), { recursive: true })
  writeFileSync(reportArg, `${JSON.stringify(report, null, 2)}\n`)
}
process.stdout.write(`config composition adversarial: ${counts.pass}/${results.length} passed; fixtures cleaned=${cleaned}\n`)
if (counts.fail || !cleaned) process.exit(1)
