// The corpus intentionally combines multiple hostile conditions in each disposable Git fixture.
// Every invalid invocation must select the frozen first error, emit stable public provenance, and
// leave the complete working tree plus staged state byte/inode/mtime-identical. Legal dependency-
// graph cycles remain legal; include recursion does not.

