function expectedDetail(envelope, expected, label) {
  assert.equal(envelope.ok, false, `${label}: invalid case reported ok`)
  assert.equal(envelope.kind, 'invalid-config', `${label}: unstable top-level kind`)
  assert.equal(envelope.detail?.code, expected.code, `${label}: wrong composition detail code`)
  if (Object.hasOwn(expected, 'source')) assert.equal(envelope.detail?.source, expected.source, `${label}: wrong source`)
  if (Object.hasOwn(expected, 'pointer')) assert.equal(envelope.detail?.pointer, expected.pointer, `${label}: wrong pointer`)
  if (expected.includeChain) assert.deepEqual(envelope.detail?.includeChain, expected.includeChain, `${label}: wrong include chain`)
  const allowed = ['code', 'conflicts', 'includeChain', 'location', 'origins', 'pointer', 'source']
  assert.deepEqual(Object.keys(envelope.detail || {}).sort(),
    Object.keys(envelope.detail || {}).filter((key) => allowed.includes(key)).sort(),
    `${label}: detail exposed an unapproved field`)
}

function invalidCase({ name, args, expected, setup, minimal, afterCommit, verify }) {
  define(name, minimal, () => {
    const root = initRepo(name)
    setup(root)
    commitAll(root)
    afterCommit?.(root)
    const before = wholeState(root)
    const result = cli(root, args)
    assertRun(result, name, 2)
    const envelope = parseEnvelope(result, name)
    expectedDetail(envelope, expected, name)
    verify?.(envelope, result)
    assert(result.stderr.trim().length > 0, `${name}: JSON failure lacked stderr diagnostic parity`)
    assertNoLeak(result, root, name)
    assert.deepEqual(wholeState(root), before, `${name}: invalid invocation mutated tree/index state`)
    assert.equal(readFileSync(join(root, 'generator-ran.sentinel'), 'utf8'), 'NOT-RUN\n', `${name}: generator ran`)
    assert.equal(readFileSync(graphPath(root), 'utf8'), expected.priorGraph || 'PRIOR-GRAPH-SENTINEL\n', `${name}: graph sentinel changed`)
    return { exit: result.status, code: envelope.detail.code, stdoutHash: sha256(result.stdout), stderrHash: sha256(result.stderr) }
  })
}

